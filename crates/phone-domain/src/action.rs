use crate::*;

#[derive(Clone, Debug)]
pub enum Action {
    Navigate(Route),
    Back,
    Home,
    Pin(AppId),
    PinTarget(TileTarget),
    PinApp {
        app: String,
        path: String,
        title: String,
    },
    SetExtensionEnabled {
        app: String,
        enabled: bool,
    },
    Unpin(Id),
    ResizeTile(Id),
    SetTileSize(Id, TileSize),
    SetTileAppearance { id: Id, appearance: TileAppearance },
    PublishTileNotification { id: Id, notification: TileNotification },
    ClearTileNotifications { id: Id, tag: Option<String> },
    DissolveFolder(Id),
    MoveIntoFolder { tile: Id, folder: Id },
    MoveTile {
        id: Id,
        before: Option<Id>,
    },
    MoveTileRelative {
        id: Id,
        target: Id,
        after: bool,
    },
    CreateFolder {
        source: Id,
        target: Id,
        name: String,
    },
    RenameFolder {
        id: Id,
        name: String,
    },
    RemoveFromFolder {
        id: Id,
        app: AppId,
    },
    ExtractFolderTile {
        folder: Id,
        tile: Id,
    },
    MoveFolderTile {
        folder: Id,
        tile: Id,
        before: Option<Id>,
    },
    SetSettings(Settings),
    ToggleSetting(String),
    Document(DocumentAction),
    Browser(BrowserAction),
    MailBatch {
        ids: Vec<Id>,
        operation: MailOperation,
    },
    ConversationBatch {
        ids: Vec<Id>,
        delete: bool,
    },
    DeleteMessage {
        conversation: Id,
        message: Id,
    },
    SaveContact(Contact),
    DeleteContact(Id),
    ToggleFavoriteContact(Id),
    SaveNote(Note),
    DeleteNote(Id),
    Calendar(CalendarAction),
    SaveEvent(CalendarEvent),
    DeleteEvent(Id),
    SaveAlarm(Alarm),
    DeleteAlarm(Id),
    ToggleAlarm(Id),
    SavePhoto(Photo),
    DeletePhoto(Id),
    ToggleFavoritePhoto(Id),
    MarkMail {
        id: Id,
        read: bool,
    },
    ToggleFlagMail(Id),
    DeleteMail(Id),
    MarkConversationRead(Id),
    DeleteConversation(Id),
    SaveConversation(Conversation),
    DraftMessage {
        id: Id,
        text: String,
    },
    AddCall(CallRecord),
    SaveBookmark(Bookmark),
    DeleteBookmark(Id),
    SaveTrack(MediaTrack),
    DeleteTrack(Id),
    ClearNotifications,
    DismissNotification(Id),
    DismissAppNotifications(AppId),
    AddNotification(Notification),
    Install(AppId),
    Uninstall(AppId),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MailOperation {
    Read,
    Unread,
    Flag,
    Unflag,
    Delete,
    Restore,
}
