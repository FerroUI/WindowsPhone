use crate::*;

#[derive(Clone, Debug)]
pub enum Action {
    Navigate(Route),
    Back,
    Home,
    Pin(AppId),
    PinTarget(TileTarget),
    Unpin(Id),
    ResizeTile(Id),
    SetTileSize(Id, TileSize),
    MoveTile {
        id: Id,
        before: Option<Id>,
    },
    MoveTileRelative {
        id: Id,
        target: Id,
        after: bool,
    },
    CreateFolder {
        source: Id,
        target: Id,
        name: String,
    },
    RenameFolder {
        id: Id,
        name: String,
    },
    RemoveFromFolder {
        id: Id,
        app: AppId,
    },
    ExtractFolderTile {
        folder: Id,
        tile: Id,
    },
    MoveFolderTile {
        folder: Id,
        tile: Id,
        before: Option<Id>,
    },
    SetSettings(Settings),
    ToggleSetting(String),
    SaveContact(Contact),
    DeleteContact(Id),
    ToggleFavoriteContact(Id),
    SaveNote(Note),
    DeleteNote(Id),
    SaveEvent(CalendarEvent),
    DeleteEvent(Id),
    SaveAlarm(Alarm),
    DeleteAlarm(Id),
    ToggleAlarm(Id),
    SavePhoto(Photo),
    DeletePhoto(Id),
    ToggleFavoritePhoto(Id),
    MarkMail {
        id: Id,
        read: bool,
    },
    ToggleFlagMail(Id),
    DeleteMail(Id),
    MarkConversationRead(Id),
    DeleteConversation(Id),
    SaveConversation(Conversation),
    DraftMessage {
        id: Id,
        text: String,
    },
    AddCall(CallRecord),
    SaveBookmark(Bookmark),
    DeleteBookmark(Id),
    SaveTrack(MediaTrack),
    DeleteTrack(Id),
    ClearNotifications,
    DismissNotification(Id),
    AddNotification(Notification),
    Install(AppId),
    Uninstall(AppId),
}
